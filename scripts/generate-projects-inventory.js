#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

// Configure this to your Projects root if different.
const PROJECTS_DIR = process.env.PROJECTS_DIR || 'C:/Users/jparris@ltu.edu.au/OneDrive - LA TROBE UNIVERSITY/Desktop/Projects';
const APPS_TS_PATH = path.join(__dirname, '..', 'src', 'data', 'apps.ts');
const PUBLIC_JSON_PATH = path.join(__dirname, '..', 'public', 'projects-inventory.json');

// Basic patterns to skip — can be extended via env SKIP_PATTERNS (comma separated)
const DEFAULT_SKIP_PATTERNS = [
    'node_modules',
    '.git',
    'VSCode',
    'npm-',
    '.zip',
    '.lnk',
    'backup',
    'Backup',
    'untracked',
    'Installers',
];

function slugify(name) {
    return name
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)/g, '');
}

function fileUrlFor(folderName) {
    // Use forward slashes and percent-encode spaces
    const encoded = folderName.replace(/ /g, '%20');
    return `file:///${PROJECTS_DIR.replace(/\\/g, '/')}/${encoded}`;
}

function makeSkeleton(folderName) {
    const id = slugify(folderName);
    const localUrl = fileUrlFor(folderName);
    const readmeLocal = `${localUrl}/README.md`;
    return `  {
        id: "${id}",
        name: "${folderName}",
        type: "app",
        category: "Apps",
        status: "wip",
        tags: ["auto-generated"],
        primaryUrl: "${localUrl}",
        urls: [
            { label: "Local folder", url: "${localUrl}" },
            { label: "README", url: "${readmeLocal}" }
        ],
        notes: "Auto-generated skeleton entry. Edit src/data/apps.ts to customise.",
        lastTouched: "${new Date().toISOString().slice(0, 7)}",
    },\n`;
}

function makeJsonEntry(folderName) {
    const id = slugify(folderName);
    const localPath = path.join(PROJECTS_DIR, folderName);
    const readmePath = path.join(localPath, 'README.md');
    return {
        id,
        name: folderName,
        localPath: localPath,
        fileUrl: fileUrlFor(folderName),
        readmeExists: fs.existsSync(readmePath),
        lastTouched: fs.existsSync(localPath) ? fs.statSync(localPath).mtime.toISOString().slice(0, 7) : null,
        autoGenerated: true,
    };
}

function matchesSkip(name, patterns) {
    for (const p of patterns) {
        if (!p) continue;
        if (p.startsWith('.') && name.endsWith(p)) return true;
        if (name.includes(p)) return true;
    }
    return false;
}

function main() {
    if (!fs.existsSync(PROJECTS_DIR)) {
        console.error('Projects directory not found:', PROJECTS_DIR);
        process.exit(2);
    }

    let appsTs = '';
    try {
        appsTs = fs.readFileSync(APPS_TS_PATH, 'utf8');
    } catch (err) {
        console.error('Unable to read', APPS_TS_PATH, err.message);
        process.exit(2);
    }

    // Backup original apps.ts (idempotent)
    try {
        if (!fs.existsSync(APPS_TS_PATH + '.bak')) {
            fs.writeFileSync(APPS_TS_PATH + '.bak', appsTs, 'utf8');
            console.log('Backed up', APPS_TS_PATH + '.bak');
        } else {
            console.log('Backup already exists:', APPS_TS_PATH + '.bak');
        }
    } catch (err) {
        console.warn('Could not write backup:', err.message);
    }

    const rawEntries = fs.readdirSync(PROJECTS_DIR, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .map((d) => d.name)
        .filter((name) => !name.startsWith('.'));

    const envSkip = (process.env.SKIP_PATTERNS || '').split(',').map(s => s.trim()).filter(Boolean);
    const skipPatterns = DEFAULT_SKIP_PATTERNS.concat(envSkip);

    const toAdd = [];
    const jsonInventory = [];
    for (const name of rawEntries) {
        if (matchesSkip(name, skipPatterns)) {
            // still include in JSON with a skipped flag
            jsonInventory.push({ ...makeJsonEntry(name), skipped: true });
            continue;
        }

        const id = slugify(name);
        const idRegex = new RegExp(`id:\\s*"${id}"`, 'i');
        const nameRegex = new RegExp(`name:\\s*"${name.replace(/[-\\/\\^$*+?.()|[\]{}]/g, '\\$&')}"`, 'i');

        // If either the id or the name appears in apps.ts, treat it as present
        if (idRegex.test(appsTs) || nameRegex.test(appsTs)) {
            jsonInventory.push({ ...makeJsonEntry(name), skipped: false, alreadyPresent: true });
            continue;
        }

        toAdd.push(name);
        jsonInventory.push({ ...makeJsonEntry(name), skipped: false, alreadyPresent: false });
    }

    // Write JSON inventory to public to be consumed by JoshHub UI
    try {
        const outDir = path.dirname(PUBLIC_JSON_PATH);
        if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
        fs.writeFileSync(PUBLIC_JSON_PATH, JSON.stringify({ generatedAt: new Date().toISOString(), projects: jsonInventory }, null, 2), 'utf8');
        console.log('Wrote JSON inventory to', PUBLIC_JSON_PATH);
    } catch (err) {
        console.error('Failed to write JSON inventory:', err.message);
    }

    if (toAdd.length === 0) {
        console.log('No missing top-level Projects folders detected (nothing to add to apps.ts).');
        return;
    }

    // Prepare skeleton entries
    const skeletons = toAdd.map(makeSkeleton).join('');

    // Insert before the trailing array close '];' that ends the apps array
    // Use a regex for the insertion point that matches a typical structure in apps.ts
    const markerRegex = /\];\s*\r?\n\s*export function getAppById/;
    if (!markerRegex.test(appsTs)) {
        console.error('Unable to find insertion point in apps.ts — file structure unexpected. Aborting apps.ts modification.');
        console.log('To inspect manually, open', APPS_TS_PATH);
        process.exit(3);
    }

    const newAppsTs = appsTs.replace(markerRegex, '\n' + skeletons + '];\n\nexport function getAppById');

    try {
        fs.writeFileSync(APPS_TS_PATH, newAppsTs, 'utf8');
        console.log('Inserted', toAdd.length, 'skeleton entries into', APPS_TS_PATH);
        console.log('Added:', toAdd.join(', '));
    } catch (err) {
        console.error('Failed to write apps.ts:', err.message);
    }
}

main();
